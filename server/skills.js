// Spaces match any whitespace so "REST\nAPI" from a wrapped PDF line still counts.
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\/#]/g, '\\$&').replace(/ /g, '\\s+')
// (?<![\w+#.]) / (?![\w+#]) act as word boundaries that also work for c++, c#, .net
const PATTERNS = Object.entries(SKILLS).map(([skill, aliases]) => [
  skill,
  new RegExp(`(?<![\\w+#.])(?:${aliases.map(esc).join('|')})(?![\\w+#])`, 'i'),
])

export function findSkills(text) {
  return PATTERNS.filter(([, re]) => re.test(text)).map(([s]) => s)
}

// Free-text skills a user typed (e.g. "java, kafka, some-new-tool") -> canonical where known.
export function normalizeSkills(list) {
  return [...new Set(list.map((s) => s.trim().toLowerCase()).filter(Boolean).map((s) => findSkills(s)[0] || s))]
}
